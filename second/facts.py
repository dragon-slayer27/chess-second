"""Turn engine analysis into verified, plain-English facts about critical moments.

Every sentence produced here is generated by code from Stockfish output and
python-chess board logic. The language model is only allowed to rephrase them.
"""

from __future__ import annotations

import math
import re
from dataclasses import asdict, dataclass

import chess

from .engine import GameAnalysis, MoveEval, win_percent
from .motifs import (
    PIECE_NAME,
    captured_piece_type,
    color_name,
    fork_targets,
    hanging_pieces,
    is_back_rank_mate,
    material_swing,
    play_line,
)

SQUARE_RE = re.compile(r"(?<![A-Za-z0-9])[a-h][1-8](?![A-Za-z0-9])")
PIECE_WORD_RE = re.compile(r"\b(king|queen|rook|bishop|knight|pawn)s?\b", re.I)
SAN_PIECE = {"K": "king", "Q": "queen", "R": "rook", "B": "bishop", "N": "knight"}
LINE_PLIES = 8


@dataclass
class Moment:
    kind: str  # "mistake" or "good"
    judgement: str | None
    ply: int
    move_number: int
    color: str
    label: str
    played: str
    best: str | None
    best_line: list[str]
    reply_line: list[str]
    eval_before: str
    eval_after: str
    score_before: str
    score_after: str
    win_before: float
    win_after: float
    sentences: list[str]
    themes: list[str]
    mates: list[int]
    fen_before: str
    fen_after: str
    played_uci: str
    best_uci: str | None
    reply_uci: str | None
    highlight: list[str]
    allowed_sans: list[str]
    allowed_squares: list[str]
    allowed_pieces: list[str]
    min_move_number: int
    max_move_number: int

    def to_dict(self) -> dict:
        return asdict(self)


def strip_check(san: str) -> str:
    return san.rstrip("+#")


def san_piece(san: str) -> str:
    san = strip_check(san)
    if san.startswith("O-O"):
        return "king"
    return SAN_PIECE.get(san[:1], "pawn")


def eval_words(cp: int, mate: int | None) -> str:
    """Describe a score from the student's point of view."""
    if mate is not None and mate > 0:
        return "a forced checkmate for you"
    if mate is not None and mate < 0:
        return "a forced checkmate for your opponent"
    if cp >= 300:
        return "winning for you"
    if cp >= 150:
        return "clearly better for you"
    if cp >= 50:
        return "slightly better for you"
    if cp > -50:
        return "about equal"
    if cp > -150:
        return "slightly worse for you"
    if cp > -300:
        return "clearly worse for you"
    return "losing for you"


def score_text(cp: int, mate: int | None, delivered: bool = False) -> str:
    if delivered:
        return "checkmate"
    if mate is not None:
        return f"#{mate}" if mate > 0 else f"#-{abs(mate)}"
    return f"{cp / 100:+.1f}"


def _pair(targets: list[dict], owner: str) -> str:
    first, second = targets[0], targets[1]
    return f"{owner} {first['piece']} on {first['square']} and {owner} {second['piece']} on {second['square']}"


def build_moment(m: MoveEval, kind: str = "mistake") -> Moment:
    board = m.board_before
    after = m.board_after
    you = m.color
    played = m.san
    sentences: list[str] = []
    themes: list[str] = []
    mates: list[int] = []
    highlight: list[str] = []

    best = m.best_move if m.best_move in board.legal_moves else None
    best_san = board.san(best) if best else None
    _, best_line = play_line(board, m.best_pv, LINE_PLIES)
    reply_moves = m.after.best.pv if m.after.best else []
    _, reply_line = play_line(after, reply_moves, LINE_PLIES)
    reply = reply_moves[0] if reply_moves and reply_moves[0] in after.legal_moves else None
    reply_san = reply_line[0] if reply_line else None

    if kind == "good":
        _good_sentences(m, after, sentences, themes, mates)
    else:
        sentences.append(
            f"Before {played} the position was {eval_words(m.cp_before, m.mate_before)}; "
            f"after it, the position was {eval_words(m.cp_after, m.mate_after)}."
        )
        if m.mate_after is not None and m.mate_after < 0:
            n = -m.mate_after
            mates.append(n)
            start = f", starting with {reply_san}" if reply_san else ""
            sentences.append(f"After {played}, your opponent has a forced checkmate in {n}{start}.")
            themes.append("allowed checkmate")
            mate_board, _ = play_line(after, reply_moves, 2 * n - 1)
            if is_back_rank_mate(mate_board):
                king = mate_board.king(you)
                sentences.append(
                    f"It would be a back-rank checkmate: your king on {chess.square_name(king)} "
                    "is stuck on its back rank."
                )
                themes.append("back-rank mate")
        if m.missed_mate and best_san:
            mates.append(m.mate_before)
            sentences.append(f"You had a forced checkmate in {m.mate_before}, starting with {best_san}.")
            themes.append("missed checkmate")

        mated = "allowed checkmate" in themes
        for item in [] if mated else hanging_pieces(after, you)[:2]:
            if item["defended"]:
                detail = f"can be taken by the {item['attacker']} on {item['attacker_square']}, which is worth less"
            else:
                detail = f"is attacked by the {item['attacker']} on {item['attacker_square']} and nothing defends it"
            sentences.append(f"After {played}, your {item['piece']} on {item['square']} {detail}.")
            highlight.append(item["square"])
            if "hanging piece" not in themes:
                themes.append("hanging piece")

        loss = material_swing(after, reply_moves, you)
        if reply is not None and reply_san and not mated:
            captured = captured_piece_type(after, reply)
            if captured:
                square = chess.square_name(reply.to_square)
                sentences.append(
                    f"Your opponent's best reply is {reply_san}, which captures your "
                    f"{PIECE_NAME[captured]} on {square}."
                )
            else:
                sentences.append(f"Your opponent's best reply is {reply_san}.")
            reply_board = after.copy()
            reply_board.push(reply)
            targets = fork_targets(reply_board, reply.to_square)
            if targets and (loss <= -2 or targets[0]["piece"] == "king"):
                sentences.append(f"{reply_san} attacks {_pair(targets, 'your')} at the same time (a fork).")
                themes.append("fork")
        if loss <= -2 and not mated:
            shown = ", ".join(reply_line[:4])
            sentences.append(
                f"If your opponent finds the best line ({shown}), you lose about {-loss} points of material."
            )
            if "hanging piece" not in themes and "fork" not in themes:
                themes.append("loses material")

        if best_san and best and best != m.move:
            best_board = board.copy()
            best_board.push(best)
            text = f"The better move was {best_san}"
            captured = captured_piece_type(board, best)
            if captured:
                text += f", which captures the opponent's {PIECE_NAME[captured]} on {chess.square_name(best.to_square)}"
                if not board.attackers(not you, best.to_square):
                    text += " for free"
                    themes.append("free piece")
            if best_board.is_checkmate():
                text += " and it is checkmate" if captured else ", which is checkmate"
            elif best_board.is_check():
                text += " and gives check" if captured else ", which gives check"
            sentences.append(text + ".")
            gain = material_swing(board, m.best_pv, you)
            targets = fork_targets(best_board, best.to_square)
            if targets and (gain >= 2 or targets[0]["piece"] == "king"):
                sentences.append(f"{best_san} attacks {_pair(targets, 'the')} at the same time (a fork).")
                themes.append("missed fork")
            if gain >= 2 and "missed checkmate" not in themes:
                shown = ", ".join(best_line[:4])
                sentences.append(f"Following the best line ({shown}), you would win about {gain} points of material.")
                if "free piece" not in themes and "missed fork" not in themes:
                    themes.append("missed win of material")
        if not themes:
            themes.append("better move available")

    allowed_sans = {strip_check(s) for s in [played, best_san, *best_line, *reply_line] if s}
    squares = set()
    for move in [m.move, best, *m.best_pv[:LINE_PLIES], *reply_moves[:LINE_PLIES]]:
        if move is not None:
            squares.update({chess.square_name(move.from_square), chess.square_name(move.to_square)})
    for sentence in sentences:
        squares.update(SQUARE_RE.findall(sentence))
    pieces = {"king"} | {san_piece(s) for s in allowed_sans}
    for sentence in sentences:
        pieces.update(word.lower() for word in PIECE_WORD_RE.findall(sentence))
    longest = max(len(best_line), len(reply_line), 1)

    return Moment(
        kind=kind,
        judgement=m.judgement,
        ply=m.ply,
        move_number=m.move_number,
        color=color_name(you).lower(),
        label=m.label,
        played=played,
        best=best_san,
        best_line=best_line,
        reply_line=reply_line,
        eval_before=eval_words(m.cp_before, m.mate_before),
        eval_after=eval_words(m.cp_after, m.mate_after),
        score_before=score_text(m.cp_before, m.mate_before),
        score_after=score_text(m.cp_after, m.mate_after, m.delivered_mate),
        win_before=round(m.win_before, 1),
        win_after=round(m.win_after, 1),
        sentences=sentences,
        themes=themes,
        mates=sorted(set(mates)),
        fen_before=board.fen(),
        fen_after=after.fen(),
        played_uci=m.move.uci(),
        best_uci=best.uci() if best else None,
        reply_uci=reply.uci() if reply else None,
        highlight=highlight,
        allowed_sans=sorted(allowed_sans),
        allowed_squares=sorted(squares),
        allowed_pieces=sorted(pieces),
        min_move_number=max(1, m.move_number - 1),
        max_move_number=m.move_number + math.ceil(longest / 2) + 1,
    )


def _good_sentences(m: MoveEval, after: chess.Board, sentences: list[str], themes: list[str], mates: list[int]) -> None:
    board = m.board_before
    played = m.san
    if m.delivered_mate:
        sentences.append(f"{m.label} was checkmate. You finished the game!")
        themes.append("checkmate")
        return
    sentences.append(f"{m.label} was the best move in the position, and the other moves were clearly worse.")
    themes.append("only move")
    captured = captured_piece_type(board, m.move)
    if captured:
        sentences.append(
            f"{played} captures the opponent's {PIECE_NAME[captured]} on {chess.square_name(m.move.to_square)}."
        )
    if after.is_check():
        sentences.append(f"{played} gives check.")
    targets = fork_targets(after, m.move.to_square)
    line = [m.move, *(m.after.best.pv if m.after.best else [])]
    gain = material_swing(board, line, m.color)
    if targets and (gain >= 2 or targets[0]["piece"] == "king"):
        sentences.append(f"{played} attacks {_pair(targets, 'the')} at the same time (a fork).")
        themes.append("fork")
    if m.mate_after is not None and m.mate_after > 0:
        mates.append(m.mate_after)
        sentences.append(f"After {played}, you have a forced checkmate in {m.mate_after}.")
        themes.append("checkmate attack")
    elif gain >= 2:
        sentences.append(f"With the best play after {played}, you win about {gain} points of material.")
        themes.append("wins material")


def select_moments(analysis: GameAnalysis, color: chess.Color, limit: int) -> list[MoveEval]:
    """The student's most important mistakes, in game order."""
    own = [m for m in analysis.moves if m.color == color]
    serious = [m for m in own if m.judgement in ("blunder", "mistake") or m.missed_mate]
    ranked = sorted(serious, key=lambda m: (m.missed_mate or m.judgement == "blunder", m.win_drop), reverse=True)
    chosen = ranked[:limit]
    wanted = min(2, limit)
    if len(chosen) < wanted:
        extra = sorted(
            (m for m in own if m.judgement == "inaccuracy" and m not in chosen),
            key=lambda m: m.win_drop,
            reverse=True,
        )
        chosen += extra[: wanted - len(chosen)]
    return sorted(chosen, key=lambda m: m.ply)


def select_good_moment(analysis: GameAnalysis, color: chess.Color) -> MoveEval | None:
    """A move worth praising: a checkmate, or a non-obvious 'only move'."""
    own = [m for m in analysis.moves if m.color == color]
    for move in own:
        if move.delivered_mate:
            return move
    best_gap, chosen = 0.0, None
    for index, move in enumerate(analysis.moves):
        if move.color != color or not move.is_best or move.second_cp is None:
            continue
        board = move.board_before
        if board.is_check() or board.legal_moves.count() <= 2:
            continue
        previous = analysis.moves[index - 1] if index > 0 else None
        if (
            previous
            and previous.board_before.is_capture(previous.move)
            and move.move.to_square == previous.move.to_square
        ):
            continue  # a recapture is rarely worth praising
        gap = win_percent(move.cp_before) - win_percent(move.second_cp)
        if gap >= 15 and gap > best_gap and move.win_after >= 40:
            best_gap, chosen = gap, move
    return chosen
